classdef ThemeManager
    % THEMEMANAGER Central palette + typography source for the whole toolkit.
    %
    %   Every component calls neuramed.core.ThemeManager.palette(themeName)
    %   instead of hard-coding colors, so a single edit here restyles every
    %   viewer, dashboard, and report in every Neura-Med AI product.
    %
    % Usage:
    %   pal = neuramed.core.ThemeManager.palette("Dark");
    %   fig.Color = pal.Background;

    methods (Static)
        function pal = palette(themeName)
            arguments
                themeName (1,1) string {mustBeMember(themeName, ["Light","Dark"])} = "Light"
            end
            switch themeName
                case "Dark"
                    pal = struct( ...
                        "Background",      [0.098 0.106 0.129], ... % #191B21
                        "Surface",         [0.145 0.157 0.184], ... % #252830
                        "SurfaceAlt",      [0.184 0.196 0.227], ...
                        "GridLine",        [0.290 0.310 0.345], ...
                        "TextPrimary",     [0.925 0.937 0.949], ...
                        "TextSecondary",   [0.635 0.655 0.690], ...
                        "Accent",          [0.259 0.678 0.961], ... % clinical blue
                        "AccentAlt",       [0.360 0.780 0.600], ... % signal green
                        "Warning",         [0.976 0.694 0.243], ...
                        "Critical",        [0.937 0.325 0.314], ...
                        "ChannelColors",   neuramed.core.ThemeManager.channelSet("Dark") ...
                        );
                case "Light"
                    pal = struct( ...
                        "Background",      [0.976 0.980 0.984], ...
                        "Surface",         [1.000 1.000 1.000], ...
                        "SurfaceAlt",      [0.933 0.941 0.949], ...
                        "GridLine",        [0.827 0.843 0.863], ...
                        "TextPrimary",     [0.110 0.125 0.157], ...
                        "TextSecondary",   [0.400 0.420 0.450], ...
                        "Accent",          [0.086 0.463 0.824], ...
                        "AccentAlt",       [0.114 0.588 0.404], ...
                        "Warning",         [0.816 0.541 0.043], ...
                        "Critical",        [0.827 0.184 0.184], ...
                        "ChannelColors",   neuramed.core.ThemeManager.channelSet("Light") ...
                        );
            end
        end

        function colors = channelSet(themeName)
            % Consistent multi-channel palette (colorblind-safe, Okabe-Ito based)
            base = [ ...
                0.902 0.624 0.000; ...
                0.337 0.706 0.914; ...
                0.000 0.620 0.451; ...
                0.941 0.894 0.259; ...
                0.000 0.447 0.698; ...
                0.835 0.369 0.000; ...
                0.800 0.475 0.655];
            if themeName == "Dark"
                colors = min(base * 1.15, 1);
            else
                colors = base;
            end
        end

        function fonts = typography()
            fonts = struct( ...
                "Family",       "Segoe UI", ...
                "TitleSize",    16, ...
                "SubtitleSize", 12, ...
                "BodySize",     10, ...
                "MonoFamily",   "Consolas");
        end

        function applyFigureTheme(fig, themeName)
            arguments
                fig
                themeName (1,1) string = "Light"
            end
            pal = neuramed.core.ThemeManager.palette(themeName);
            fig.Color = pal.Background;
        end
    end
end
